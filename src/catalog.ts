const categoryTitles: Record<CatalogCategory, string> = {
  application: "Application",
  base: "Base",
  marketing: "Marketing",
};

const marketingDocumentationRoutes: Readonly<Record<string, string>> = {
  banners: "banners",
  blog: "blog-sections",
  careers: "careers-sections",
  contact: "contact-sections",
  content: "content-rich-text-sections",
  cta: "cta-sections",
  faq: "faq-sections",
  features: "features-sections",
  footers: "footers",
  "header-navigation": "header-navigations",
  "header-section": "header-sections",
  metrics: "metrics-sections",
  "newsletter-cta": "newsletter-cta-sections",
  "pricing-sections": "pricing-sections",
  "social-proof": "social-proof-sections",
  "team-sections": "team-sections",
  testimonials: "testimonial-sections",
};

const titleWords: Readonly<Record<string, string>> = {
  ai: "AI",
  md: "MD",
  pin: "PIN",
  sm: "SM",
  twofa: "Two-factor",
  xs: "XS",
};

const titleFromSlug = (slug: string): string =>
  slug
    .split("-")
    .map((part) => titleWords[part] ?? `${part.slice(0, 1).toUpperCase()}${part.slice(1)}`)
    .join(" ");

const evidenceById: Readonly<Record<string, VerificationEvidence>> = verifiedEvidence;

const documentationUrl = (entry: CatalogSourceEntry): string => {
  if (entry.category !== "marketing") {
    return entry.documentationUrl;
  }
  const route = marketingDocumentationRoutes[entry.family];
  return route === undefined
    ? entry.documentationUrl
    : `https://www.untitledui.com/react/marketing/${route}/${entry.id}`;
};

const catalogFamily = (entry: CatalogSourceEntry): string => {
  if (entry.family !== "root") {
    return entry.family;
  }
  const sourceFamily = entry.sourcePath.split("/").at(3);
  if (sourceFamily === undefined || sourceFamily === "root") {
    return entry.id;
  }
  return sourceFamily;
};

const toCatalogEntry = (entry: CatalogSourceEntry): CatalogEntry => {
  const family = catalogFamily(entry);
  const storybookFamily = entry.category === "marketing" ? `/${titleFromSlug(family)}` : "";
  const storybookTitle = `Untitled UI/${categoryTitles[entry.category]}${storybookFamily}/${titleFromSlug(entry.id)}`;
  const verification = evidenceById[entry.id];
  if (verification !== undefined) {
    return {
      accessLevel: "authenticated",
      category: entry.category,
      dependencies: ["foldkit", "effect", "tokens"],
      documentationUrl: documentationUrl(entry),
      documentedVariants: verification.documentedVariants,
      family,
      id: entry.id,
      sourcePath: entry.sourcePath,
      sourceVersion: entry.sourceVersion,
      status: "verified",
      storybookTitle,
      verification,
    };
  }
  return {
    accessLevel: "authenticated",
    category: entry.category,
    dependencies: [],
    documentationUrl: documentationUrl(entry),
    documentedVariants: [],
    family,
    id: entry.id,
    sourcePath: entry.sourcePath,
    sourceVersion: entry.sourceVersion,
    status: entry.status,
    storybookTitle,
  };
};

export const catalog: readonly CatalogEntry[] = catalogSource.map(toCatalogEntry);

export const verifiedCatalog = catalog.filter((entry) => entry.status === "verified");
